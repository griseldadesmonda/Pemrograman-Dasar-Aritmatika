public class Variabel004 {
    public static void main(String[] args) {
        int Bilangan1, Bilangan2;

        Bilangan1 = 21;
        Bilangan2 = 7;

        System.out.println("Bilangan 1 = " + Bilangan1);
        System.out.println("Bilangan 2 = " + Bilangan2);
        System.out.println("Hasil Pembagian : 21 / 7 =  " + Bilangan1 / Bilangan2);
        System.out.println("Hasil Perkalian : 21 x 7 = " + Bilangan1 * Bilangan2);
        System.out.println("Hasil Pengurangan : 21 - 7 = " + (Bilangan1 - Bilangan2));
        System.out.println("Hasil Penjumlahan : 21 + 7 = " + (Bilangan1 + Bilangan2));
    }
}
